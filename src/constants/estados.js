// Converte a UF recebida da API na opção exibida pelo react-select.
// O backend continua recebendo/enviando a sigla em `value`.
export const getEstadoOption = (uf) => {
  if (!uf) return null;

  const value = typeof uf === "string" ? uf.trim().toUpperCase() : uf.value;
  return estados.find((estado) => estado.value === value) || {
    value,
    label: value,
  };
};
